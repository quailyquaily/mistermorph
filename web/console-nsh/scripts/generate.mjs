#!/usr/bin/env node
// Writes lib/generated/*: what the Vue console got from Vite's `?raw` and `import.meta.glob`
// imports, which nsh's bundler does not have. Run it after changing assets/config or the
// icon folders: `node scripts/generate.mjs`.
import { readdirSync, readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const app = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(app, "..", "..");
const out = join(app, "lib", "generated");
mkdirSync(out, { recursive: true });

const header = "// Generated by scripts/generate.mjs. Do not edit.\n";
const text = (path) => readFileSync(join(repo, path), "utf8");

// Config templates the setup flow writes (setup-contract.js, soul-presets.js).
const templates = {
  heartbeatTemplate: "assets/config/HEARTBEAT.md",
  identityTemplate: "assets/config/persona/identity.yaml",
  cronTemplate: "assets/config/cron.yaml",
  soulTemplate: "assets/config/persona/soul.md",
  catSoulTemplate: "assets/config/souls/cat.md",
  dogSoulTemplate: "assets/config/souls/dog.md",
  researchScholarSoulTemplate: "assets/config/souls/research_scholar.md",
  softwareEngineerSoulTemplate: "assets/config/souls/software_engineer.md",
};
let body = header;
for (const [name, path] of Object.entries(templates)) {
  body += `export const ${name} = ${JSON.stringify(text(path))};\n`;
}
body += `export const soulPresetManifest = ${text("assets/config/souls/presets.json").trim()};\n`;
writeFileSync(join(out, "config-templates.js"), body);

// An image map per folder: file name without .svg -> the imported asset.
function iconMap(folder, file) {
  const names = readdirSync(join(app, "assets", folder))
    .filter((name) => name.endsWith(".svg"))
    .sort();
  let source = header;
  names.forEach((name, index) => {
    source += `import i${index} from "../../assets/${folder}/${name}";\n`;
  });
  source += "\nexport default {\n";
  names.forEach((name, index) => {
    source += `  ${JSON.stringify(name.replace(/\.svg$/u, ""))}: i${index},\n`;
  });
  source += "};\n";
  writeFileSync(join(out, file), source);
}
iconMap("workspace-icons", "workspace-icons.js");
iconMap("topic-icons", "topic-icons.js");
