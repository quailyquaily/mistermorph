#!/usr/bin/env node
// Writes lib/vendor/jsqr.js: jsQR's browser build (dist/jsQR.js of the npm package `jsqr`) as one
// string, for the QR scanner's page (lib/qrScannerPage.js). That page runs in a web view and the
// app's own code is compiled, so its scripts are kept as text. jsQR reads a QR code from a frame's
// pixels where the web view has no `BarcodeDetector` (the iPhone's WebKit).
//
//   npm pack jsqr@1.4.0 && tar -xzf jsqr-1.4.0.tgz
//   node scripts/vendor-jsqr.mjs package/dist/jsQR.js 1.4.0
//
// Its licence (Apache-2.0) is lib/vendor/jsqr-LICENSE, copied from the same package.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const [source, version] = process.argv.slice(2);
if (!source || !version) {
  console.error("usage: node scripts/vendor-jsqr.mjs <path to dist/jsQR.js> <version>");
  process.exit(1);
}
const code = readFileSync(source, "utf8");
if (!code.includes('root["jsQR"] = factory()')) {
  console.error(`${source} is not jsQR's browser build (it defines no global jsQR)`);
  process.exit(1);
}
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "lib", "vendor", "jsqr.js");
writeFileSync(
  out,
  `// jsQR ${version} (https://github.com/cozmo/jsQR), its browser build as text, for the QR scanner's
// page (lib/qrScannerPage.js). Apache-2.0: lib/vendor/jsqr-LICENSE. Generated by
// scripts/vendor-jsqr.mjs; do not edit.
export const JSQR_VERSION = ${JSON.stringify(version)};
export const JSQR_SOURCE = ${JSON.stringify(code)};
`,
);
console.log(`wrote ${out} (${code.length} characters of jsQR ${version})`);
